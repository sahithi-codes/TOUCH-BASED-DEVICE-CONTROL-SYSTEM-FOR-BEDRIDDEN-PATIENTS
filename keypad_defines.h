//keypad_defines.h  - 4x4 matrix pin definitions

#ifndef KEYPAD_DEFINES_H
#define KEYPAD_DEFINES_H

//keypad row pin definitions

#define ROW0 16         //Row0 connected to port1 pin 16(P1.16)
#define ROW1 17         //Row1 connected to port1 pin 17(P1.17)
#define ROW2 18         //Row2 connected to port1 pin 18(P1.18)
#define ROW3 19         //Row3 connected to port1 pin 19(P1.19)

//keypad column pin definitions

#define COL0 20         //Col0 connected to port1 pin 20(P1.20)
#define COL1 21         //Col1 connected to port1 pin 21(P1.21)
#define COL2 22         //Col2 connected to port1 pin 22(P1.22)
#define COL3 23         //Col3 connected to port1 pin 23(P1.23)

#endif                  //end of KEYPAD_DEFINES_H